# Usage:
#   gen-zvvm-intrinsics.py --tests DIR
#     Write DIR/zvmma-mmacc-table.c, which calls every intrinsic of
#     zvvm-mmacc.def in its default form.
#   gen-zvvm-intrinsics.py --check-spec SPEC.adoc
#     List the rows of the specification's floating-point encoding map
#     (tbl-fp-encoding-map) that zvvm-mmacc.def lacks, and the entries of
#     zvvm-mmacc.def that the encoding map lacks.  Exit with status 1 if
#     there are any.

import argparse
import os
import re
import sys

TABLE = os.path.join (os.path.dirname (os.path.abspath (__file__)),
                      "zvvm-mmacc.def")

# Vector type name and intrinsic type suffix of each format.
TYPES = {
  "FP16": ("vfloat16", "f16"),
  "BF16": ("vbfloat16", "bf16"),
  "FP32": ("vfloat32", "f32"),
  "FP64": ("vfloat64", "f64"),
  "E4M3": ("vfloat8e4m3", "f8e4m3"),
  "E5M2": ("vfloat8e5m2", "f8e5m2"),
}

# Rows of the encoding map that zvvm-mmacc.def leaves to the same-format
# vfmmacc function group.
SAME_FORMAT_VFMMACC = {("vfmmacc", f, f, f)
                       for f in ("FP16", "BF16", "FP32", "FP64")}


def read_table ():
  """Return the entries of zvvm-mmacc.def as (NAME, INSN, C, A, B)."""
  text = open (TABLE).read ()
  rows = []
  for m in re.finditer (r"^IME_(?:FP|OFP8)_MMACC \(([^)]*)\)", text,
                        re.M):
    args = [a.strip () for a in m.group (1).split (",")]
    rows.append (tuple (args[:5]))
  return rows


def intrinsic (insn, c, a, b):
  """Return the name of the default form of an intrinsic, with an m1
     accumulator and LMUL=1 inputs."""
  name = "__riscv_%s_vv_%sm1" % (insn, TYPES[c][1])
  # Inputs whose type differs from the accumulator's are named; a
  # second input is named if it differs from the first.
  if a != c or b != c or c in ("E4M3", "E5M2"):
    name += "_%sm1" % TYPES[a][1]
    if b != a:
      name += "_%sm1" % TYPES[b][1]
  return name


def write_tests (directory):
  rows = read_table ()
  out = []
  out.append ("/* Generated by gen-zvvm-intrinsics.py from zvvm-mmacc.def;"
              " do not edit.  */\n")
  out.append ("/* { dg-do compile } */\n")
  out.append ("/* { dg-options \"-march=rv64gcv_zbb_zvmma_zvfh_zvfbfmin"
              " -mabi=lp64d -O2\" } */\n\n")
  out.append ("typedef __SIZE_TYPE__ size_t;\n")
  out.append ("#pragma riscv intrinsic \"vector\"\n")
  for name, insn, c, a, b in rows:
    out.append ("\n%sm1_t\n%s (%sm1_t vd, %sm1_t vs1, %sm1_t vs2,"
                " size_t vl)\n{\n  return %s (vd, vs1, vs2, vl);\n}\n"
                % (TYPES[c][0], name, TYPES[c][0], TYPES[a][0],
                   TYPES[b][0], intrinsic (insn, c, a, b)))
  out.append ("\n")
  for insn in sorted ({r[1] for r in rows}):
    out.append ("/* { dg-final { scan-assembler {\\m%s\\.vv\\M} } } */\n"
                % insn)
  path = os.path.join (directory, "zvmma-mmacc-table.c")
  open (path, "w").write ("".join (out))


def read_spec (path):
  """Return the rows of the specification's floating-point encoding map
     as (INSN, C, A, B), without the reserved ones."""
  text = open (path).read ()
  start = text.index ("[#tbl-fp-encoding-map]")
  body = text[text.index ("|===", start) + 4:]
  body = body[:body.index ("|===")]
  rows = set ()
  for line in body.splitlines ():
    cells = [c.strip () for c in line.split ("|")[1:]]
    if len (cells) < 10 or cells[0] == "Instruction":
      continue
    insn, a, b, c, ext = cells[0], cells[4], cells[6], cells[8], cells[9]
    if "_reserved_" in ext or "—" in (a, b, c):
      continue
    rows.add ((insn, c, a, b))
  return rows


def check_spec (path):
  spec = read_spec (path)
  ours = {(insn, c, a, b) for _, insn, c, a, b in read_table ()}
  ours |= SAME_FORMAT_VFMMACC
  status = 0
  for title, rows in (("In the encoding map but not in zvvm-mmacc.def",
                       spec - ours),
                      ("In zvvm-mmacc.def but not in the encoding map",
                       ours - spec)):
    if rows:
      status = 1
      print ("%s:" % title)
      for insn, c, a, b in sorted (rows):
        print ("  %-9s %s x %s -> %s" % (insn, a, b, c))
  return status


def main ():
  parser = argparse.ArgumentParser ()
  parser.add_argument ("--tests", metavar="DIR")
  parser.add_argument ("--check-spec", metavar="SPEC")
  args = parser.parse_args ()
  if not args.tests and not args.check_spec:
    parser.error ("specify --tests or --check-spec")
  status = 0
  if args.tests:
    write_tests (args.tests)
  if args.check_spec:
    status = check_spec (args.check_spec)
  return status


if __name__ == "__main__":
  sys.exit (main ())
